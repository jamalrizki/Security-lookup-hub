// Lookup page wiring. All output goes through textContent / el(): nothing
// user-supplied or fetched is ever parsed as HTML.

import { detect, defang, identifyHash } from './detect.js';
import { linksFor } from './links.js';
import { md5, toHex } from './md5.js';
import { CODECS } from './encoding.js';
import { checkPassword } from './pwned.js';
import { API_BASE } from './config.js';
import { sourceCard, priorityStrip } from './results.js';

const $ = (id) => document.getElementById(id);
const TYPE_LABELS = { cve: 'CVE ID', ipv4: 'IPv4 address', ipv6: 'IPv6 address', domain: 'Domain', url: 'URL', email: 'Email address' };
const utf8 = new TextEncoder();

function el(tag, attrs = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (k === 'class') node.className = v;
    else node.setAttribute(k, v);
  }
  for (const c of children) if (c != null) node.append(c);
  return node;
}

function notice(kind, ...children) {
  return el('p', { class: `notice ${kind}` }, ...children);
}

function externalLink(href, ...children) {
  return el('a', { href, target: '_blank', rel: 'noopener noreferrer' }, ...children);
}

async function sha(algo, bytes) {
  return toHex(new Uint8Array(await crypto.subtle.digest(algo, bytes)));
}

// ---------- Search ----------

let searchRun = 0;

/** Query string for /api/lookup and /api/explain; the DKIM selector only for domains and emails. */
function lookupParams(d) {
  const p = new URLSearchParams({ q: d.value });
  const sel = $('dkim-input').value.trim();
  if (sel && ['domain', 'email'].includes(d.type)) p.set('dkim', sel);
  return p.toString();
}

async function fetchResults(d, box) {
  const run = ++searchRun;
  box.replaceChildren(el('p', { class: 'hint' }, 'Checking sources\u2026'));
  let body;
  let status;
  try {
    const res = await fetch(`${API_BASE}/api/lookup?${lookupParams(d)}`, { referrerPolicy: 'no-referrer' });
    status = res.status;
    body = await res.json();
  } catch {
    body = { error: 'The lookup service could not be reached. The links below still work.' };
  }
  if (run !== searchRun) return; // a newer search replaced this one
  if (body.error) {
    box.replaceChildren(notice(status === 429 ? 'bad' : 'warn', body.error));
    return;
  }
  if (!body.sources.length) {
    box.replaceChildren(el('p', { class: 'hint' }, body.note));
    return;
  }
  box.replaceChildren(...[
    d.type === 'url' ? el('p', { class: 'hint' }, `Results are for the URL\u2019s host, ${defang(d.host)}.`) : null,
    body.priority ? priorityStrip(body.priority) : null,
    d.type === 'email' ? el('p', { class: 'hint' }, 'Results are for the email domain. Breach checks for an address need Have I Been Pwned\u2019s site (their email API is paid).') : null,
    // Results first; skipped or failed sources go last (sort is stable).
    el('div', { class: 'cards' }, ...[...body.sources]
      .sort((a, b) => ['skipped', 'error'].includes(a.status) - ['skipped', 'error'].includes(b.status))
      .map(sourceCard)),
    explainPanel(d),
    d.type === 'cve' ? el('p', { class: 'hint' }, 'Want to ask questions about it? ',
      el('a', { href: 'https://jamalrizki.github.io/cve-explainer/', target: '_blank', rel: 'noopener noreferrer' }, 'Try CVE Explainer \u2192')) : null,
  ].filter(Boolean));
}

// On demand only: nothing is sent to the AI provider unless the visitor asks.
function explainPanel(d) {
  const panel = el('section', { class: 'explain', 'aria-live': 'polite' });
  const button = el('button', { type: 'button', class: 'secondary' }, 'Explain these results');
  const intro = el('p', { class: 'hint' },
    'Writes a plain-English summary with an AI model (gpt-oss-120b on Groq). The results above are sent to Groq; your IP address and anything else are not. AI can be wrong, so check the cards.');
  button.addEventListener('click', async () => {
    button.disabled = true;
    button.textContent = 'Explaining\u2026';
    let body;
    try {
      const res = await fetch(`${API_BASE}/api/explain?${lookupParams(d)}`, { referrerPolicy: 'no-referrer' });
      body = await res.json();
    } catch {
      body = { error: 'The explainer could not be reached.' };
    }
    if (body.error) {
      panel.replaceChildren(button, notice('warn', body.error));
      button.disabled = false;
      button.textContent = 'Try again';
      return;
    }
    panel.replaceChildren(
      el('h3', {}, 'AI summary'),
      el('div', { class: 'explain-text' }, body.explanation),
      el('p', { class: 'hint' }, `Generated by ${body.model}${body.cached ? ' (cached)' : ''}. AI can be wrong; the cards above are the evidence.`),
    );
  });
  panel.append(button, intro);
  return panel;
}

function renderSearch(raw) {
  const out = $('search-result');
  const d = detect(raw);
  // The DKIM selector field only makes sense for domain and email lookups.
  $('dkim-row').hidden = !['domain', 'email'].includes(d.type);
  out.replaceChildren();
  if (d.type === 'empty') return;

  if (d.type === 'unknown') {
    out.append(notice('warn', d.error));
    return;
  }

  const shown = d.type === 'url' || d.type === 'domain' ? defang(d.value) : d.value;
  out.append(el('div', { class: 'detected' },
    el('span', { class: 'badge' }, d.label || TYPE_LABELS[d.type] || d.type),
    el('span', { class: 'mono' }, shown)));

  if (d.error) {
    out.append(notice('warn', d.error));
    return;
  }

  const results = el('div', { 'aria-live': 'polite' });
  out.append(results);
  fetchResults(d, results);

  out.append(el('h3', {}, 'Open in'));
  out.append(el('ul', { class: 'links' }, ...linksFor(d).map((l) =>
    el('li', {}, externalLink(l.href, el('strong', {}, l.name), el('span', { class: 'what' }, l.what))))));
}

$('search-form').addEventListener('submit', (ev) => {
  ev.preventDefault();
  renderSearch($('search-input').value);
});

// Deep links use the fragment (#q=8.8.8.8) so the indicator is never sent to the web server.
function searchFromHash() {
  const q = new URLSearchParams(location.hash.slice(1)).get('q');
  if (q) {
    $('search-input').value = q;
    renderSearch(q);
  }
}
window.addEventListener('hashchange', searchFromHash);
searchFromHash();

// ---------- Password check ----------

$('pw-form').addEventListener('submit', async (ev) => {
  ev.preventDefault();
  const out = $('pw-result');
  const password = $('pw-input').value;
  if (!password) {
    out.replaceChildren();
    return;
  }
  const button = ev.submitter || ev.target.querySelector('button[type="submit"]');
  button.disabled = true;
  try {
    const count = await checkPassword(password);
    out.replaceChildren(count > 0
      ? notice('bad', el('strong', {}, `Found ${count.toLocaleString()} times in known breaches.`),
        ' Do not use this password anywhere.')
      : notice('ok', el('strong', {}, 'Not found in known breaches.'),
        ' That does not make it strong, only not yet leaked.'));
  } catch (err) {
    out.replaceChildren(notice('warn', `Could not check: ${err.message}`));
  } finally {
    button.disabled = false;
  }
});

$('pw-toggle').addEventListener('click', (ev) => {
  const input = $('pw-input');
  const showing = input.type === 'text';
  input.type = showing ? 'password' : 'text';
  ev.target.textContent = showing ? 'Show' : 'Hide';
  ev.target.setAttribute('aria-pressed', String(!showing));
});

// ---------- Hash identifier ----------

$('hid-input').addEventListener('input', (ev) => {
  const out = $('hid-result');
  const value = ev.target.value.trim();
  if (!value) {
    out.replaceChildren();
    return;
  }
  const found = identifyHash(value);
  if (!found.length) {
    out.replaceChildren(notice('warn', 'No known hash format matches this length and character set.'));
    return;
  }
  out.replaceChildren(
    el('p', { class: 'hint' }, found.length > 1
      ? 'Possible types, most likely first. Format alone cannot tell these apart.'
      : 'Matches this format:'),
    el('ul', { class: 'candidates' }, ...found.map((h) =>
      el('li', {}, el('strong', {}, h.name), h.note ? el('span', { class: 'note' }, ` — ${h.note}`) : null))));
});

// ---------- Hash calculator ----------

const CALC = [
  ['MD5', async (b) => md5(b)],
  ['SHA-1', (b) => sha('SHA-1', b)],
  ['SHA-256', (b) => sha('SHA-256', b)],
  ['SHA-512', (b) => sha('SHA-512', b)],
];

let calcRun = 0;
async function renderCalc() {
  const run = ++calcRun;
  const bytes = utf8.encode($('calc-input').value);
  const digests = await Promise.all(CALC.map(([, fn]) => fn(bytes)));
  if (run !== calcRun) return; // a newer keystroke already started
  $('calc-result').replaceChildren(...CALC.flatMap(([name], i) => {
    const copy = el('button', { type: 'button', class: 'secondary small', 'aria-label': `Copy ${name}` }, 'Copy');
    copy.addEventListener('click', async () => {
      try {
        await navigator.clipboard.writeText(digests[i]);
        copy.textContent = 'Copied';
      } catch {
        copy.textContent = 'Blocked';
      }
      setTimeout(() => { copy.textContent = 'Copy'; }, 1200);
    });
    return [el('dt', {}, name), el('dd', {}, digests[i]), copy];
  }));
}
$('calc-input').addEventListener('input', renderCalc);
renderCalc();

// ---------- Decoder ----------

const codecSelect = $('dec-codec');
for (const [id, c] of Object.entries(CODECS)) codecSelect.append(el('option', { value: id }, c.label));

function runCodec(direction) {
  const codec = CODECS[codecSelect.value];
  const err = $('dec-error');
  try {
    $('dec-output').value = codec[direction]($('dec-input').value);
    err.replaceChildren();
  } catch (e) {
    $('dec-output').value = '';
    err.replaceChildren(notice('warn', e.message));
  }
}
$('dec-encode').addEventListener('click', () => runCodec('encode'));
$('dec-decode').addEventListener('click', () => runCodec('decode'));
$('dec-swap').addEventListener('click', () => {
  $('dec-input').value = $('dec-output').value;
  $('dec-output').value = '';
  $('dec-error').replaceChildren();
});
