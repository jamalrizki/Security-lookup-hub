"""Keeps the shared page chrome identical across pages.

Run from the repo root after adding a page, or after changing css/style.css,
js/nav.js or js/chrome.js:  python3 scripts/nav.py

For every page it (re)writes:
  - the decorative layers: binary rain, terminal bar, hex ticker (aria-hidden;
    their contents are drawn by js/chrome.js)
  - the header: brand, phone menu button, main nav
  - the hero: giant outlined title (the nav label), the page's intro
    paragraph (kept as is), and the radar with "MODULE 0N/08"; the Ask page
    (index.html) has no hero, so the chat fills the screen
  - link-preview (Open Graph / Twitter) tags and icons, from the page title
    and intro paragraph; preview image images/og-image.png (1200x630)
  - Google Analytics 4 (loader + js/analytics.js) and its CSP entries
  - script/stylesheet tags with a content hash (?v=...), so browsers never
    pair a new page with an old cached file (tests/assets.test.mjs checks it)
"""
import hashlib, pathlib, re

NAV = [
    ('./', 'index.html', 'Ask', 'ask'),
    ('lookup.html', 'lookup.html', 'Lookup', 'lookup'),
    ('analyze.html', 'analyze.html', 'Analyze', 'analyze'),
    ('cves.html', 'cves.html', 'CVEs', 'cves'),
    ('news.html', 'news.html', 'News', 'news'),
    ('actors.html', 'actors.html', 'Threat actors', 'actors'),
    ('reference.html', 'reference.html', 'Reference', 'reference'),
    ('tools.html', 'tools.html', 'Tools', 'tools'),
]
PAGES = [file for _, file, _, _ in NAV]

root = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ['css/style.css', 'js/nav.js', 'js/chrome.js', 'js/analytics.js']
VERSIONS = {a: hashlib.sha256((root / a).read_bytes()).hexdigest()[:10] for a in ASSETS}

CHROME = '''  <div class="rain" aria-hidden="true"></div>
  <div class="term" aria-hidden="true">
    <span class="term-prompt">root@slh:~/{key}#</span>
    <span class="term-line"><span class="term-cmd"></span><span class="term-cursor"></span></span>
    <span class="term-out"></span>
    <span class="term-pid">PID 0000 &middot; tty/0</span>
  </div>
'''

HEADER = '''  <header class="site-header">
    <div class="inner">
      <a class="brand" href="./" aria-label="Security Lookup Hub, home"><span class="brand-dot" aria-hidden="true"></span>SECURITY_LOOKUP_HUB</a>
      <button class="nav-toggle" type="button" aria-expanded="false" aria-controls="site-nav" hidden>
        <span class="when-closed">&#9776; MENU</span><span class="when-open">&#10005; CLOSE</span>
      </button>
      <nav class="site-nav" id="site-nav" aria-label="Main">
{links}
      </nav>
    </div>
  </header>
  <div class="ticker" aria-hidden="true"><span class="ticker-track"></span></div>
'''

HERO = '''    <section class="hero">
      <div class="hero-text">
        <h1 class="hero-title"><span class="hero-outline">{title}</span><span class="hero-fill" aria-hidden="true">{title}</span></h1>
        <p class="lede">{lede}</p>
      </div>
      <div class="radar-block" aria-hidden="true">
        <div class="radar"><span class="radar-sweep"></span><span class="radar-ring"></span><span class="radar-blip"></span><span class="radar-dot"></span></div>
        <p class="radar-caption">MODULE {num:02d}/{total:02d}<br>STATUS: ARMED</p>
      </div>
    </section>
'''

SITE = 'https://jamalrizki.github.io/Security-lookup-hub/'
GA_LOADER = '<script async src="https://www.googletagmanager.com/gtag/js?id=G-26NLWZWCNN"></script>'
# Pages without a hero keep their own compact heading (none at the moment; the Ask
# page has had the standard hero since the Matrix redesign).
NO_HERO = set()
# The home page (Ask) has no intro paragraph, so it gets a description written for sharing.
HOME_TITLE = 'Security Lookup Hub: ask a security question'
HOME_DESCRIPTION = ('Ask a security question, or look up a hash, domain, IP, URL, email or CVE. Free threat '
                    'intel from VirusTotal, AbuseIPDB, NVD, CISA KEV and more, using passive lookups only.')

def plain(html_text):
    """Intro paragraph as plain text for meta descriptions."""
    import html as htmllib
    t = re.sub(r'<[^>]+>', '', html_text)
    t = htmllib.unescape(re.sub(r'\s+', ' ', t)).strip()
    return t if len(t) <= 200 else t[:197].rsplit(' ', 1)[0] + '\u2026'

def social(title, description, url):
    """Link-preview tags (Facebook, LinkedIn, X, Slack, iMessage, ...) and icons."""
    import html as htmllib
    a = lambda v: htmllib.escape(v, quote=True)
    image = SITE + 'images/og-image.png'
    return f'''  <!-- social: generated by scripts/nav.py -->
  <meta name="description" content="{a(description)}">
  <link rel="canonical" href="{url}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Security Lookup Hub">
  <meta property="og:title" content="{a(title)}">
  <meta property="og:description" content="{a(description)}">
  <meta property="og:url" content="{url}">
  <meta property="og:image" content="{image}">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="Security Lookup Hub: one search box for hashes, domains, IPs, URLs, emails and CVEs.">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="theme-color" content="#050a06">
  <link rel="icon" href="favicon.svg" type="image/svg+xml">
  <link rel="icon" href="favicon-32.png" type="image/png" sizes="32x32">
  <link rel="apple-touch-icon" href="apple-touch-icon.png">
  <!-- /social -->
'''

existing = [p for p in PAGES if (root / p).exists()]
for page in existing:
    path = root / page
    html = path.read_text()
    i = PAGES.index(page)
    _, _, title, key = NAV[i]

    # Body: page key for js/chrome.js.
    html = re.sub(r'<body[^>]*>', f'<body data-page="{key}">', html, count=1)

    # Decorative layers right after the skip link (replaced if already there).
    html = re.sub(r'  <div class="rain".*?</div>\n  <div class="term".*?\n  </div>\n', '', html, flags=re.S)
    html = re.sub(r'(<a class="skip"[^>]*>[^<]*</a>\n)', lambda m: m.group(1) + CHROME.format(key=key), html, count=1)

    # Header + ticker.
    links = []
    for href, file, label, _ in NAV:
        if file not in existing:
            continue
        attr = ' aria-current="page"' if file == page else ''
        links.append(f'        <a href="{href}"{attr}>{label}</a>')
    header = HEADER.format(links='\n'.join(links))
    html, n = re.subn(r'  <header class="site-header">.*?</header>\n(  <div class="ticker".*?</div>\n)?', lambda m: header, html, count=1, flags=re.S)
    assert n == 1, f'{page}: no header'

    # Hero: keep the existing intro paragraph, replace the title block.
    hero = re.search(r'    <section class="hero">.*?\n    </section>\n', html, re.S)
    if page in NO_HERO:
        assert not hero, f'{page}: should have no hero'
    elif hero:
        lede = re.search(r'<p class="lede">(.*?)</p>', hero.group(0), re.S).group(1)
        span = hero.span()
    else:
        m = re.search(r'(    <p class="hint"><a href="reference.html">[^\n]*\n)?    <h1>.*?</h1>\n    <p class="lede">(.*?)</p>\n', html, re.S)
        assert m, f'{page}: no h1 + lede'
        lede, span = m.group(2), m.span()
    if page not in NO_HERO:
        html = html[:span[0]] + HERO.format(title=title, lede=lede, num=i + 1, total=len(NAV)) + html[span[1]:]

    # Link previews and icons, from the page title and intro paragraph.
    href = NAV[i][0]
    page_title = re.search(r'<title>(.*?)</title>', html).group(1)
    page_title = HOME_TITLE if page == 'index.html' else page_title
    url = SITE if href == './' else SITE + href
    html = re.sub(r'  <!-- social: generated by scripts/nav.py -->.*?<!-- /social -->\n', '', html, flags=re.S)
    html = re.sub(r'  <link rel="icon" href="favicon.svg" type="image/svg\+xml">\n', '', html)
    description = HOME_DESCRIPTION if page == 'index.html' else plain(re.search(r'<p class="lede">(.*?)</p>', html, re.S).group(1))
    html = html.replace('  <meta name="referrer" content="no-referrer">\n', '  <meta name="referrer" content="no-referrer">\n' + social(page_title, description, url), 1)
    assert 'og:image' in html, f'{page}: social tags not inserted'

    # Google Analytics 4: Google's loader plus our copy of its inline snippet, and
    # the CSP entries Google documents for GA4 (developers.google.com/tag-platform/security/guides/csp).
    if GA_LOADER not in html:
        html = html.replace('  <link rel="stylesheet" href="css/style.css', f'  {GA_LOADER}\n  <script src="js/analytics.js"></script>\n  <link rel="stylesheet" href="css/style.css', 1)
    def add_csp(directive, sources):
        csp_meta = re.search(r'(<meta http-equiv="Content-Security-Policy" content=")([^"]*)(")', html)
        policy = csp_meta.group(2)
        m = re.search(rf'(?:^|; ){directive} ([^;]*)', policy)
        current = m.group(1).split()
        missing = [x for x in sources if x not in current]
        if missing:
            policy = policy.replace(f'{directive} {m.group(1)}', f'{directive} {" ".join(current + missing)}', 1)
        return html.replace(csp_meta.group(0), csp_meta.group(1) + policy + csp_meta.group(3), 1)
    html = add_csp('script-src', ['https://www.googletagmanager.com'])
    html = add_csp('img-src', ['https://www.googletagmanager.com', 'https://*.google-analytics.com'])
    html = add_csp('connect-src', ['https://www.googletagmanager.com', 'https://*.google-analytics.com', 'https://*.google.com'])

    # Scripts and stylesheet, with cache-busting versions.
    if 'src="js/nav.js' not in html:
        html = html.replace('  <link rel="stylesheet" href="css/style.css', '  <script src="js/nav.js"></script>\n  <link rel="stylesheet" href="css/style.css', 1)
    if 'src="js/chrome.js' not in html:
        html = html.replace('  <link rel="stylesheet" href="css/style.css', '  <script type="module" src="js/chrome.js"></script>\n  <link rel="stylesheet" href="css/style.css', 1)
    for asset in ASSETS:
        html = re.sub(rf'(["\']){re.escape(asset)}(\?v=[0-9a-f]+)?(["\'])', rf'\g<1>{asset}?v={VERSIONS[asset]}\g<3>', html)

    path.write_text(html)
    print('layout updated:', page)
